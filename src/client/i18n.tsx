export type Lang = keyof typeof dict;
export type TKey = keyof (typeof dict)["ja"];

const I18nContext = createContext<{
  lang: Lang;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  setLang: (l: Lang) => void;
}>({
  lang: "ja",
  t: (key) => key,
  setLang: () => undefined,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(
    () => (localStorage.getItem("cul_lang") as Lang) ?? "ja",
  );
  const setLang = (l: Lang) => {
    localStorage.setItem("cul_lang", l);
    setLangState(l);
  };
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = (key: TKey, vars?: Record<string, string | number>) => {
    let text: string = dict[lang][key] ?? dict.ja[key] ?? key;
    if (vars)
      for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
  return <I18nContext.Provider value={{ lang, t, setLang }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
